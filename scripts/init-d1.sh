#!/usr/bin/env bash
# ==============================================================================
# اسکریپت خودکار راه‌اندازی و مایگریشن جداول پایگاه‌داده Cloudflare D1
# فروشگاه FURY_SHOP
# ==============================================================================

set -e

echo "🚀 در حال آماده‌سازی و ساخت جداول دیتابیس ir-fury-shop-db..."

# 1. ساخت و تست در حالت محلی (Local D1 State)
echo "📦 مرحله ۱: اجرای مایگریشن در محیط محلی (Local D1)..."
npx wrangler d1 execute ir-fury-shop-db --local --file=./d1-schema.sql

# 2. بررسی وجود توکن کلودفلر برای اجرای روی سرور ابری ریموت
if [ -n "$CLOUDFLARE_API_TOKEN" ]; then
  echo "🌐 مرحله ۲: توکن کلودفلر شناسایی شد؛ در حال اعمال مستقیم روی دیتابیس ابری (Remote D1)..."
  npx wrangler d1 execute ir-fury-shop-db --remote --file=./d1-schema.sql
  echo "✅ جداول با موفقیت روی دیتابیس ابری Cloudflare D1 شما ساخته شدند!"
else
  echo "ℹ️ نکته: برای اعمال روی دیتابیس آنلاین کلودفلر، توکن API کلودفلر لازم است."
  echo "   شما می‌توانید توکن خود را با دستور زیر تنظیم کنید:"
  echo "   export CLOUDFLARE_API_TOKEN=\"توکن_شما\""
  echo "   و سپس مجدداً این اسکریپت را اجرا کنید."
fi

echo "🎉 عملیات مایگریشن به پایان رسید!"
